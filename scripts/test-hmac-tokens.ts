// Tampered signatures.
function flipLastChar(token: string): string {
  const last = token.slice(-1);
  return token.slice(0, -1) + (last === 'A' ? 'B' : 'A');
}

// A wrapped state is base64url of `payload.signature`, and a base64url string's
// final character can carry bits the decoder discards — flipping it does not
// always change the decoded bytes. Tamper inside the decoded signature instead.
function tamperWrappedSignature(state: string): string {
  const decoded = Buffer.from(state, 'base64url').toString('utf8');
  const lastDot = decoded.lastIndexOf('.');
  const sig     = decoded.slice(lastDot + 1);
  const flipped = (sig[0] === '0' ? '1' : '0') + sig.slice(1);
  return Buffer.from(`${decoded.slice(0, lastDot)}.${flipped}`, 'utf8').toString('base64url');
}
