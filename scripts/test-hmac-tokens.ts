// five HMAC token kinds that now share lib/hmacToken.ts.
//
// WHY THIS SCRIPT EXISTS
// Tokens minted before the consolidation are in the wild: opt-out links live in
// email footers for a year, outreach reply tokens for 90 days, availability
// picker links for 7 days, and an OAuth state can be sitting in a browser
// mid-consent. The shared module therefore had to keep every wire format
// byte-identical. The OLD_* constants below are the proof: each was produced by
// the PRE-consolidation code (commit e71a05d) via this script's own
