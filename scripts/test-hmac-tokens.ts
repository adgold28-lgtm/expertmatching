//   AVAILABILITY_TOKEN_SECRET=<FIXTURE_SECRET below> npx tsx scripts/test-hmac-tokens.ts --emit-fixtures
// run against the old lib/optOutToken.ts, lib/outreachToken.ts,
// lib/availabilityToken.ts and lib/onboardingOauthState.ts, with Date.now()
// stubbed (see emitFixtures) so the "future" tokens carry a year-2100 expiry
// and the "past" ones a year-2020 expiry. Re-running the mode today regenerates
// them with the NEW code; the constants stay as the old code left them.
//
// FIXTURE_SECRET is not a secret: it is a throwaway 32-character string that
// exists only so the fixtures are reproducible. Nothing signed with it is
